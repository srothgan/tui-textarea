//! Deliberate trace fixtures. Regenerate their binary encoding with the seed-corpus example.
use crate::{decode::character, Target};

pub struct Seed {
    pub target: Target,
    pub name: &'static str,
    pub bytes: Vec<u8>,
}

struct Trace(Vec<u8>);

impl Trace {
    fn new(header: u8) -> Self {
        Self(vec![header])
    }
    fn op(mut self, op: u8) -> Self {
        self.0.push(op);
        self
    }
    fn bytes(mut self, bytes: &[u8]) -> Self {
        self.0.extend_from_slice(bytes);
        self
    }
    fn word(self, word: u16) -> Self {
        self.bytes(&word.to_le_bytes())
    }
    fn text(self, text: &str) -> Self {
        assert!(text.len() <= 64);
        self.bytes(&[text.len() as u8]).bytes(text.as_bytes())
    }
    fn ch(self, ch: char) -> Self {
        self.bytes(&[(0..=255).find(|byte| character(*byte) == ch).unwrap()])
    }
    fn movement(self, tag: u8, row: u16, col: u16) -> Self {
        self.bytes(&[tag]).word(row).word(col)
    }
    fn hit(self) -> Self {
        self.bytes(&[0, 0])
    }
    fn seed(self, target: Target, name: &'static str) -> Seed {
        Seed {
            target,
            name,
            bytes: self.0,
        }
    }
}

